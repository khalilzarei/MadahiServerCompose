    /**
     * حروف/کاراکتری که در جستجو باید یکسان دیده شوند
     * (عربی → فارسی و حذف نیم‌فاصله — فاصله‌ها جداگانه حذف می‌شوند)
     */
    public const SEARCH_REPLACEMENTS = [
        'ي'        => 'ی',   // ی عربی → ی فارسی
        'ك'        => 'ک',   // ک عربی → ک فارسی
        'أ'        => 'ا',
        'إ'        => 'ا',
        'آ'        => 'ا',
        'ؤ'        => 'و',
        'ئ'        => 'ی',
        'ء'        => '',
        'ة'        => 'ه',
        "\u{200C}" => '',    // نیم‌فاصله (ZWNJ) — حذف
        "\u{200D}" => '',    // اتصال‌دهنده (ZWJ) — حذف
    ];

    /**
     * اعراب/تشکیل و تطویل که در جستجو باید حذف شوند
     */
    public const SEARCH_DIACRITICS = [
        "\u{064B}", "\u{064C}", "\u{064D}",
        "\u{064E}", "\u{064F}", "\u{0650}",
        "\u{0651}", "\u{0652}", "\u{0653}",
        "\u{0654}", "\u{0655}", "\u{0656}",
        "\u{0657}", "\u{0658}", "\u{0659}",
        "\u{065A}", "\u{065B}", "\u{065C}",
        "\u{065D}", "\u{065E}", "\u{065F}",
        "\u{0640}",   // تطویل (کشیدگی)
    ];

    /**
     * نرمال‌سازی متن برای جستجو:
     * حذف اعراب + یکدست‌کردن حروف عربی/فارسی + حذف کامل فاصله‌ها
     * (فاصله معمولی، نیم‌فاصله، تب و…) تا «می‌خوانمت» با «می خوانمت»
     * و «میخوانمت» یکی شوند.
     */
    public static function normalizeSearchText(string $text): string
    {
        // ۱) حذف اعراب و تطویل
        $text = (string)preg_replace(
            '/[\x{064B}\x{064C}\x{064D}\x{064E}-\x{065F}\x{0640}]/u',
            '',
            $text
        );

        // ۲) یکدست‌کردن حروف (نیم‌فاصله هم اینجا حذف می‌شود)
        $text = str_replace(
            array_keys(self::SEARCH_REPLACEMENTS),
            array_values(self::SEARCH_REPLACEMENTS),
            $text
        );

        // ۳) حذف کامل فاصله‌ها
        $text = (string)preg_replace('/\s+/u', '', $text);
        return trim($text);
    }

    /**
     * الگوهای شکل‌های داخل پرانتز — قبل از حذف علائم نگارشی اعمال می‌شوند
     */
    private static $parenPatterns = [
