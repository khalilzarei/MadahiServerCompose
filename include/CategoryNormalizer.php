    /**
     * نرمال‌سازی عنوان → کلید گروه
     * (قدم‌های ۱ تا ۷: normalizeBase | قدم ۸: آلیاس | قدم ۹: قانون «شامل بودن»)
     */
    public static function normalize(string $title): string
    {
        $t = self::normalizeBase($title);

        // ۸) آلیاس‌های خاص (قوانین کاربر) — بدون بازگشت‌گذاری، با map کش‌شده
        if (!empty(self::ALIASES)) {
            if (self::$aliasMap === null) {
                self::$aliasMap = self::buildAliasMap();
            }
            if (isset(self::$aliasMap[$t])) {
                return self::$aliasMap[$t];
            }
        }

        // ۸.۵) یکدست‌کردن نیم‌فاصله و اتصال‌دهنده (فقط برای مرحله بعد)
        //      تا «زین‌العابدین» و «زین العابدین» یکسان دیده شوند
        $t = str_replace(["\u{200C}", "\u{200D}"], ' ', $t);
        $t = (string)preg_replace('/\s+/u', ' ', $t);
        $t = trim($t);

        // ۹) قانون «شامل بودن» (contains) — مثلاً هر نامی که «حسین» دارد
        //    به گروه «امام حسین (ع)» می‌رود. ترتیب KEYWORDS مهم است:
        //    خاص‌ترها (مثل «عسکری») قبل از عام‌ترها (مثل «حسن») چک می‌شوند
        //    تا «امام حسن عسکری» با «امام حسن» قاطی نشود.
        if (self::$keywordMap === null) {
            self::$keywordMap = self::buildKeywordMap();
        }
        foreach (self::$keywordMap as [$keyword, $canonical]) {
            if (mb_strpos($t, $keyword) !== false) {
                return $canonical;
            }
        }

        return $t;
    }

    /**
     * قدم‌های ۱ تا  نرمال‌سازی (بدون آلیاس)
     */
    private static function normalizeBase(string $title): string
    {
        $t = $title;

        // ۱) حذف تاشکیل و تطویل
        $t = (string)preg_replace('/[\\x{064B}\\x{064C}\\x{064E}-\\x{065F}\\x{0640}]/u', '', $t);

        // ۲) یکدست‌کردن حروف (عربی ← فارسی)
        $t = str_replace(
            ['ي', 'ك'],   // ي ك (عربی)
            ['ی', 'ک'],   // ی ک (فارسی)
            $t
        );

        // ۳) نیم‌فاصله ← فاصله معمولی
        $t = str_replace('ٍ', ' ', $t);

        // ۳.۵) حذف شکل‌های داخل پرانتز — حتماً قبل از حذف علائم نگارشی!
        $prev = null;
        while ($prev !== $t) {
            $prev = $t;
            foreach (self::$parenPatterns as $pattern) {
                $t = (string)preg_replace($pattern, '', $t);
            }
        }
        $t = trim($t);

        // ۴) علائم نگارشی ← فاصله
        $t = (string)preg_replace(
            '/[\x{060C}\x{061B}\x{061F}\[:;,.\?!\'"()[\]{}~_…\x{2013}\x{2014}\x{2018}\x{2019}\x{201C}\x{201D}\x{002D}]/u',
            ' ',
            $t
        );

        // ۵) حروف لاتین lowercase
        if (function_exists('mb_strtolower')) {
            $t = mb_strtolower($t, 'UTF-8');
        }

        // ۶) جمع‌کردن فاصله‌ها
        $t = (string)preg_replace('/\s+/u', ' ', $t);
        $t = trim($t);

        // ۷) حذف پسوندهای ارجاعی (تا ثبات برسد)
        $prev = null;
        while ($prev !== $t) {
            $prev = $t;
            foreach (self::$suffixPatterns as $pattern) {
                $t = (string)preg_replace($pattern, '', $t);
            }
            $t = trim($t);
        }

        return $t;
    }

    /**
     * map آلیاس: (شکل جایگزین نرمال‌شده) ← (نام اصلی)
     * یک‌بار برای کل درخواست ساخته می‌شود (کش استاتیک) — بدون بازگشت‌گذاری
     */
    private static $aliasMap = null;

    private static function buildAliasMap(): array
    {
        $map = [];
        foreach (self::ALIASES as $canonical => $variants) {
            $map[self::normalizeBase($canonical)] = $canonical;
            foreach ($variants as $variant) {
                $map[self::normalizeBase($variant)] = $canonical;
            }
        }
        return $map;
    }
